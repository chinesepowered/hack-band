"""LLM brains for the herd, from any OpenAI-compatible endpoint.

Set LLM_BASE_URL, LLM_API_KEY and LLM_MODEL to switch it on. The model writes
every agent's lines in character and makes the negotiation moves (Mochi's
asks, each supplier's concessions). Code still owns the guardrails: prices are
clamped to each side's limits, and the tables the agents parse are always
generated by code. Without the variables, or whenever a call fails, agents
fall back to their built-in lines and policy, so a run never stalls.
"""

from __future__ import annotations

import asyncio
import json
import logging
import os
import re
from typing import Any

import httpx

log = logging.getLogger("capybargain")

STYLE = (
    "Speak as yourself, in first person. Write one or two short sentences, at most 30 words. "
    "Be warm, cute and playful, with at most two emoji. No markdown, lists, tables, hashtags, "
    "stage directions or asterisks. Only use numbers you were given."
)

_client: httpx.AsyncClient | None = None


def enabled() -> bool:
    return bool(os.environ.get("LLM_API_KEY") and os.environ.get("LLM_MODEL"))


def model_name() -> str:
    return os.environ.get("LLM_MODEL", "")


def _http() -> httpx.AsyncClient:
    global _client
    if _client is None:
        _client = httpx.AsyncClient(
            base_url=os.environ.get("LLM_BASE_URL", "https://api.openai.com/v1").rstrip("/"),
            headers={"Authorization": f"Bearer {os.environ['LLM_API_KEY']}"},
            timeout=httpx.Timeout(40.0, connect=10.0),
        )
    return _client


async def _complete(messages: list[dict[str, str]], *, json_mode: bool, max_tokens: int) -> str:
    body: dict[str, Any] = {
        "model": model_name(),
        "messages": messages,
        "max_tokens": max_tokens,
        "temperature": 0.8,
        "reasoning_effort": "none",  # short in-character replies don't need a reasoning pass
    }
    if json_mode:
        body["response_format"] = {"type": "json_object"}
    error: Exception | None = None
    for attempt in range(5):  # some endpoints return a random 500 now and then; retries are cheap
        try:
            resp = await _http().post("/chat/completions", json=body)
            resp.raise_for_status()
            return resp.json()["choices"][0]["message"].get("content") or ""
        except (httpx.HTTPError, KeyError, ValueError) as exc:
            error = exc
            await asyncio.sleep(0.4 * (attempt + 1))
    raise RuntimeError(f"LLM call failed: {error}")


def tidy(text: str, limit: int = 220) -> str:
    """Strip reasoning blocks, quotes, stage directions and markdown; keep it short."""
    text = re.sub(r"<think>.*?</think>", "", text, flags=re.S)
    text = re.sub(r"(?<!\*)\*(?!\*)[^*\n]{1,80}\*(?!\*)", "", text)  # *blows a bubble*
    text = text.replace("**", "").replace("#", "").replace("|", "/").strip().strip('"').strip()
    text = " ".join(text.split())
    if len(text) > limit:
        cut = max(text.rfind(p, 0, limit) for p in ".!?")
        text = text[: cut + 1] if cut > limit // 3 else text[:limit].rstrip() + "…"
    return text


PRICE = re.compile(r"\$\s?\d|\d+\.\d{2}\b|\d+\s*(?:cents?|dollars?|bucks)\b", re.IGNORECASE)


def without_prices(text: str) -> str:
    """Drop sentences that state a price: the table under the line is the source of truth."""
    sentences = re.split(r"(?<=[.!?])\s+", text)
    return " ".join(s for s in sentences if not PRICE.search(s)).strip()


async def line(persona: str, task: str, *, fallback: str, facts: str = "", prices: bool = True) -> str:
    """One short in-character line, or ``fallback`` if the model is off or fails.

    With ``prices=False``, sentences that state a price are dropped, for lines
    that sit on top of a code-written price table.
    """
    if not enabled():
        return fallback
    try:
        text = tidy(
            await _complete(
                [
                    {"role": "system", "content": f"{persona}\n\n{STYLE}"},
                    {"role": "user", "content": f"{facts}\n\n{task}".strip()},
                ],
                json_mode=False,
                max_tokens=160,
            )
        )
    except Exception as exc:  # noqa: BLE001
        log.warning("LLM line failed, using the built-in one: %s", exc)
        return fallback
    if not prices:
        text = without_prices(text)
    return text or fallback


async def decide(persona: str, task: str, *, facts: str, fallback: dict[str, Any]) -> dict[str, Any]:
    """A small JSON decision, or ``fallback`` if the model is off, fails or returns junk."""
    if not enabled():
        return fallback
    try:
        raw = await _complete(
            [
                {
                    "role": "system",
                    "content": f"{persona}\n\nFor any line you write for others to read: {STYLE}\n\n"
                    "Reply with a single JSON object only.",
                },
                {"role": "user", "content": f"{facts}\n\n{task}"},
            ],
            json_mode=True,
            max_tokens=320,
        )
        found = re.search(r"\{.*\}", raw, flags=re.S)
        data = json.loads(found.group(0) if found else raw)
        if not isinstance(data, dict):
            raise ValueError("not an object")
        return data
    except Exception as exc:  # noqa: BLE001
        log.warning("LLM decision failed, using the built-in policy: %s", exc)
        return fallback
